// Writes public/brand/mapa-orkana.svg (under `/brand`: a folder `proxy.ts` already serves) — the address map of the shared elements (`AddressMap`, spec §5,
// §9) from the OSM drawing in src/lib/shared/osmMap.generated.ts (made by software-osm-map.mjs).
// A static file the browser caches between pages instead of ~60 KB of paths in every page's HTML
// (D2-1b review). Coordinates rounded to whole units (no drift: absolute first, then relative);
// colours as `style="…var(--am-…)"`, so the `<use>` element's CSS variables pick light or dark.
// Run: node scripts/address-map-svg.mjs  (the unit test fails when the file is out of date)
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const DATA = new URL('../src/lib/shared/osmMap.generated.ts', import.meta.url)
const OUT = new URL('../public/brand/mapa-orkana.svg', import.meta.url)

/** The OSM drawing object of the generated module (its JSON literal). */
export function readOsm(file = DATA) {
  const source = readFileSync(file, 'utf8')
  return JSON.parse(source.slice(source.indexOf('{'), source.lastIndexOf('}') + 1))
}

const num = (n) => String(n === 0 ? 0 : n)

/**
 * An `M`/`l`/`z` path with every point rounded to a whole unit: points are made absolute, rounded,
 * then written relative again — so rounding never adds up along a line. Zero-length steps go.
 */
export function roundPath(d) {
  const tokens = d.match(/[Mlz]|-?\d*\.?\d+/g) ?? []
  let out = ''
  let command = ''
  let x = 0
  let y = 0
  let rx = 0
  let ry = 0
  let pending = []
  const flush = () => {
    if (pending.length) out += `l${pending.join(' ').replace(/ -/g, '-')}`
    pending = []
  }
  for (let i = 0; i < tokens.length; i++) {
    const token = tokens[i]
    if (token === 'M' || token === 'l' || token === 'z') {
      command = token
      if (token === 'z') {
        flush()
        out += 'z'
      }
      continue
    }
    const a = Number(token)
    const b = Number(tokens[++i])
    if (command === 'M') {
      flush()
      x = a
      y = b
      rx = Math.round(x)
      ry = Math.round(y)
      out += `M${num(rx)} ${num(ry)}`.replace(/ -/g, '-')
      command = 'l'
      continue
    }
    x += a
    y += b
    const nx = Math.round(x)
    const ny = Math.round(y)
    if (nx === rx && ny === ry) continue
    pending.push(`${num(nx - rx)} ${num(ny - ry)}`)
    rx = nx
    ry = ny
  }
  flush()
  return out
}

const ROAD = 'fill:none;stroke-linecap:round;stroke-linejoin:round'

/** The SVG document: one `<g id="map">` to `<use>`, in the drawing's 800 × 560 coordinates. */
export function buildAddressMapSvg(osm = readOsm()) {
  const { layers } = osm
  const path = (d, style) => `<path d="${roundPath(d)}" style="${style}"/>`
  const label = osm.labels.find((item) => item.text === 'ul. Orkana')
  const parts = [
    `<rect x="-400" y="-400" width="1600" height="1360" style="fill:var(--am-land)"/>`,
    path(layers.green, 'fill:var(--am-park)'),
    path(layers.wood, 'fill:var(--am-wood)'),
    path(layers.park, 'fill:var(--am-parking)'),
    path(layers.water, 'fill:var(--am-water)'),
    path(layers.ww, `${ROAD};stroke:var(--am-water);stroke-width:5`),
    path(layers.b, 'fill:var(--am-block);stroke:var(--am-block-line);stroke-width:.8'),
    path(layers.r4, `${ROAD};stroke:var(--am-path);stroke-dasharray:3 3;stroke-width:1.4`),
    path(layers.r3, `${ROAD};stroke:var(--am-casing);stroke-width:7`),
    path(layers.r2, `${ROAD};stroke:var(--am-casing);stroke-width:11`),
    path(layers.r1, `${ROAD};stroke:var(--am-casing);stroke-width:16`),
    path(layers.r3, `${ROAD};stroke:var(--am-road);stroke-width:4.5`),
    path(layers.r2, `${ROAD};stroke:var(--am-road);stroke-width:8`),
    path(layers.r1, `${ROAD};stroke:var(--am-road-main);stroke-width:12.5`),
    path(layers.rail, 'fill:none;stroke:var(--am-rail);stroke-dasharray:10 6;stroke-width:3'),
    path(osm.target, 'fill:var(--am-accent)'),
  ]
  if (label) {
    parts.push(
      `<text transform="translate(${Math.round(label.x)} ${Math.round(label.y)}) rotate(${Math.round(label.angle)})" text-anchor="middle" dy="-6" style="fill:var(--am-label);stroke:var(--am-land);stroke-width:4px;stroke-linejoin:round;paint-order:stroke;font-size:12px;font-weight:800">${label.text}</text>`,
    )
  }
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${osm.width} ${osm.height}">`,
    `<!-- Data © OpenStreetMap contributors, ODbL (https://www.openstreetmap.org/copyright). Generated by scripts/address-map-svg.mjs. -->`,
    `<g id="map">${parts.join('')}</g>`,
    `</svg>`,
    '',
  ].join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, buildAddressMapSvg())
  console.log(`public/brand/mapa-orkana.svg written (${Buffer.byteLength(buildAddressMapSvg())} B)`)
}
