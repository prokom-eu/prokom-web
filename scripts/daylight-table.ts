/**
 * Writes `src/lib/shared/daylight.generated.ts`: the 24-number sunrise/sunset table of Rabka-Zdrój
 * for the inline theme script (ADR-028). Run after changing `daylight.ts`:
 *   node scripts/daylight-table.ts && pnpm prettier --write src/lib/shared/daylight.generated.ts
 * `daylight.test.ts` fails when the committed file differs from the function.
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

import { buildDaylightTable } from '../src/lib/shared/daylight.ts'

const target = fileURLToPath(new URL('../src/lib/shared/daylight.generated.ts', import.meta.url))
const table = buildDaylightTable()

writeFileSync(
  target,
  `// Generated by scripts/daylight-table.ts — do not edit by hand.
/** Sunrise, sunset on the 15th of each month in Rabka-Zdrój, minutes of the day in UTC+1. */
export const DAYLIGHT_TABLE: readonly number[] = ${JSON.stringify(table)}
`,
)
console.log(`daylight.generated.ts: ${table.join(', ')}`)
