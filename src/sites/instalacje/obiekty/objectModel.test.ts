// The reference: the prototype's own class (`zrodlo/pages/Seg*.js`, generated by
// `build_seg.py`), run with a `setState` that merges, so clicks and the autoplay run there too.
const PAGES: Record<BuiltObjectKey, string> = {
  dom: 'SegDom',
  apt: 'SegApartament',
  hotel: 'SegHotel',
  rest: 'SegRestauracja',
  sklep: 'SegSklep',
  firma: 'SegFirma',
  kosc: 'SegKosciol',
  szk: 'SegSzkola',
  gmina: 'SegGmina',
  dev: 'SegDeweloper',
  bud: 'SegBudowa',
}
const read = (file: string) =>
  readFileSync(
    fileURLToPath(
      new URL(`../../../../docs/design/prokominstalacje/zrodlo/pages/${file}`, import.meta.url),
    ),
    'utf8',
  )

type Pick = { pick: () => void; cls: string; on: string }
type Ref = {
  sg: {
    hc: Record<string, string>
    hp: Record<string, () => void>
    leg: (Pick & { t: string; no: string })[]
    ly: (Pick & { n: string })[]
    cur: { no: string; t: string }
    pos: string
    prev: () => void
    next: () => void
    prepLead: string
    day: {
      pg: string
      items: Pick[]
      cur: { hs: { no: string; pick: () => void }[] }
    }
    ck: { n: number; t: number; st: string; cta: string; items: Pick[] }
  }
}
type Proto = {
  state: Record<string, unknown>
  initState(): Record<string, unknown>
  mountPage(): void
  page(P: unknown, c: unknown): Ref
  ticks: (() => void)[]
}
const P = new Proxy({}, { get: (_, key) => String(key) })

function prototype(key: BuiltObjectKey): Proto {
  const Class = new Function(
    `return class { ${read(`${PAGES[key]}.js`)}
      sub(c, o) { return o }
      setState(o) { Object.assign(this.state, o) }
      every(ms, fn) { (this.ticks = this.ticks || []).push(fn.bind(this)) } }`,
  )() as new () => Proto
  const proto = new Class()
  proto.state = proto.initState()
  proto.ticks = []
  // No `document`/`window` in the test: `calm()` catches and says „not calm”, so ticks run.
  proto.mountPage()
  return proto
}
const render = (proto: Proto) => proto.page(P, {}).sg

/** Our view of the scene, in the prototype's shape, for one state. */
function ours(key: BuiltObjectKey, s: SceneState) {
  const hotspots = OBJECT_SCENES[key].hotspots
  return {
    hc: Object.fromEntries(hotspots.map((_, i) => [`k${i}`, hotspotClass(i, s, hotspots)])),
    leg: hotspots.map((_, i) => legendClass(i, s, hotspots)),
    ly: visibleLayers(hotspots).map((l) => l.label),
    cur: String(s.hs + 1),
    pos: scenePosition(s, hotspots.length),
  }
}
const theirs = (sg: Ref['sg']) => ({
  hc: sg.hc,
  leg: sg.leg.map((l) => l.cls),
  ly: sg.ly.map((l) => l.n),
  cur: sg.cur.no,
  pos: sg.pos,
})

const KEYS = Object.keys(PAGES) as BuiltObjectKey[]

describe.each(KEYS)('object page %s — the same as the prototype', (key) => {
  const hotspots = OBJECT_SCENES[key].hotspots

  it('has the hotspot titles of the prototype, in the same order', () => {
    expect(render(prototype(key)).leg.map((l) => l.t)).toEqual(hotspots.map((h) => h.title))
  })

  it('hotspots, legend, layers and prev/next follow the same steps', () => {
    const proto = prototype(key)
    let s = INITIAL_SCENE
    const check = () => expect(ours(key, s)).toEqual(theirs(render(proto)))
    check()
    // Autoplay twice, a hotspot, next ×2, previous.
    for (const tick of [0, 0]) {
      proto.ticks[tick]?.()
      s = autoplayScene(s, hotspots.length)
      check()
    }
    render(proto).hp['k3']?.()
    s = pickHotspot(s, 3)
    check()
    render(proto).next()
    s = stepHotspot(s, 1, hotspots)
    render(proto).next()
    s = stepHotspot(s, 1, hotspots)
    check()
    render(proto).prev()
    s = stepHotspot(s, -1, hotspots)
    check()
    // Every layer button, with prev/next inside the layer.
    render(proto).ly.forEach((_, i) => {
      const layer = visibleLayers(hotspots)[i]
      render(proto).ly[i]?.pick()
      s = pickLayer(s, layer?.key ?? '', hotspots)
      check()
      render(proto).next()
      s = stepHotspot(s, 1, hotspots)
      check()
      render(proto).prev()
      render(proto).prev()
      s = stepHotspot(stepHotspot(s, -1, hotspots), -1, hotspots)
      check()
    })
    // The autoplay keeps running after a touch only in the prototype's tick — it checks `tch`.
    proto.ticks[0]?.()
    check()
  })

  it('day timeline: classes, progress and the hotspots of each moment', () => {
    const proto = prototype(key)
    const length = render(proto).day.items.length
    let dy = 0
    for (let step = 0; step < length + 1; step++) {
      const sg = render(proto)
      expect(sg.day.items.map((d) => d.cls)).toEqual(
        Array.from({ length }, (_, i) => dayClass(i, dy)),
      )
      expect(sg.day.pg).toBe(`width:${dayProgress(dy, length)}%`)
      proto.ticks[1]?.()
      dy = autoplayDay(dy, length)
    }
    // „Na przekroju” of the current moment → that hotspot, all layers.
    const sg = render(proto)
    const nums = sg.day.cur.hs.map((h) => Number(h.no) - 1)
    const source = read(`${PAGES[key]}.js`)
    const D = JSON.parse(source.match(/D = (\{.*?\});\n/s)?.[1] ?? '{}') as {
      day: { items: { s: ServiceKey[] }[] }
    }
    expect(nums).toEqual(dayHotspots(D.day.items[dy]?.s ?? [], hotspots))
    const last = sg.day.cur.hs.at(-1)
    if (last) {
      render(proto).ly[1]?.pick()
      last.pick()
      expect(ours(key, pickFromDay(Number(last.no) - 1))).toEqual(theirs(render(proto)))
    }
  })

  it('checklist: count, ring and button text', () => {
    const proto = prototype(key)
    const total = render(proto).ck.t
    const checked: boolean[] = []
    for (let i = 0; i <= total; i++) {
      const sg = render(proto)
      const c = checklist(checked, total)
      expect([sg.ck.n, sg.ck.st]).toEqual([c.n, `--p:${c.ratio}`])
      expect(sg.ck.cta).toBe(c.done ? 'Gotowe, wyślij zgłoszenie →' : 'Wyślij zdjęcia i opis →')
      if (i < total) {
        sg.ck.items[i]?.pick()
        checked[i] = true
      }
    }
    expect(prepareLead(key, null)).toBe(render(proto).prepLead)
  })

  it('scene markup: one hotspot per title, classes and colours filled in', () => {
    const art = OBJECT_SCENE_ART[key]
    const html = sceneHtml(art.html, INITIAL_SCENE, hotspots, () => '#123456')
    expect(html).not.toMatch(/%[a-z]/)
    expect(html.match(/data-k="/g)).toHaveLength(hotspots.length)
    expect(html).toContain('class="hs on" data-k="0" style="--c:#123456"')
    hotspots.forEach((h, i) => expect(html).toContain(`aria-label="${i + 1}. ${h.title}"`))
  })
})

describe('layers', () => {
  it('lists „Wszystko” first, then only the layers of the object', () => {
    expect(LAYERS[0]?.key).toBe('')
    expect(visibleLayers([{ title: 'x', service: 'ev' }]).map((l) => l.key)).toEqual(['', 'kom'])
  })
})
